// Development-only extraction. Browser verification loads these hosted files
// automatically; there is no file picker or player-provided disc path.
import fs from 'node:fs';
import path from 'node:path';
import {parseFileTable, parseHeader} from '../../web/lib/disc.ts';
import {fighterArchives} from '../../engines/browser-native/fighter-assets.mjs';
const root=path.resolve(import.meta.dirname,'../..');
const filename=process.argv[2];
if(!filename)throw Error('Pass the development USA 1.02 fixture path. This is a build tool, not player setup.');
const fd=fs.openSync(filename,'r');
const shared=['PlCo.dat','PdPm.dat','IfAll.usd','ItCo.usd','PlKbCpMr.dat','PlKbCpLg.dat','PlKbCpDr.dat','PlKbCpCa.dat','PlKbCpGn.dat','PlKbCpNs.dat','PlKbCpPe.dat','PlKbCpFx.dat','PlKbCpPk.dat','PlKbCpPc.dat','PlKbCpLk.dat','PlKbCpCl.dat','PlKbCpSs.dat','PlKbCpFc.dat','PlKbNrCpFc.dat','PlKbCpDk.dat','PlKbNrCpDk.dat','PlKbCpMs.dat','PlKbCpFe.dat'];
const effects=['EfCoData.dat','EfCaData.dat','EfDkData.dat','EfMsData.dat','EfGnData.dat','EfFeData.dat','EfFxData.dat','EfPrData.dat','EfMrData.dat','EfLgData.dat','EfPkData.dat','EfSsData.dat','EfKpData.dat','EfLkData.dat','EfYsData.dat','EfMtData.dat','EfNsData.dat','EfZdData.dat','EfPeData.dat','EfIcData.dat','EfKbData.dat','EfKbMr.dat','EfKbLg.dat','EfKbCa.dat','EfKbGn.dat','EfKbFx.dat','EfKbPk.dat','EfKbSs.dat','EfKbDk.dat','EfKbMs.dat','EfKbFe.dat'];
const names=['GrNBa.dat','GrNLa.dat','GrOp.dat','GrSt.dat','GrIz.dat','GrPs.usd'];
const fighters=Object.keys(fighterArchives).map(code=>'Pl'+code+'.dat');
const animations=Object.keys(fighterArchives).map(code=>'Pl'+code+'AJ.dat');
const models=Object.keys(fighterArchives).map(code=>'Pl'+code+'Nr.dat');
const output=path.join(root,'dist/native-port');
function read(offset,size) {
  const bytes=Buffer.alloc(size);
  if(fs.readSync(fd,bytes,0,size,offset)!==size)throw Error('Truncated development fixture');
  return bytes;
}
try {
  const total=fs.fstatSync(fd).size;
  const header=parseHeader(read(0,0x440).buffer,total);
  const files=parseFileTable(read(header.fstOffset,header.fstSize).buffer,total);
  fs.mkdirSync(path.join(output,'fixtures'),{recursive:true});
  for(const name of [...shared,...effects,...names,...fighters,...animations,...models]) {
    const file=files.find(f=>f.path===name);
    if(!file)throw Error('Development asset missing: '+name);
    fs.writeFileSync(path.join(output,'fixtures',name),read(file.offset,file.size));
  }
  // Original SIS atlas from the development executable; generated bytes stay
  // in ignored build output and are never requested from players.
  const discHeader=read(0,0x440),dolOffset=discHeader.readUInt32BE(0x420),dol=read(dolOffset,0x100);
  const address=0x8040CD40,length=287*512;let font;
  for(let i=0;i<18;i++) {
    const offset=dol.readUInt32BE(i*4),base=dol.readUInt32BE(0x48+i*4),size=dol.readUInt32BE(0x90+i*4);
    if(address>=base&&address+length<=base+size)font=read(dolOffset+offset+address-base,length);
  }
  if(!font)throw Error('Original SIS font lies outside the executable sections');
  fs.writeFileSync(path.join(output,'fixtures','sis-font.bin'),font);
  fs.writeFileSync(path.join(output,'shared-fixtures.json'),JSON.stringify(shared,null,2)+'\n');
  fs.writeFileSync(path.join(output,'effect-fixtures.json'),JSON.stringify(effects,null,2)+'\n');
  fs.writeFileSync(path.join(output,'stage-fixtures.json'),JSON.stringify(names,null,2)+'\n');
  fs.writeFileSync(path.join(output,'fighter-fixtures.json'),JSON.stringify(fighters,null,2)+'\n');
  fs.writeFileSync(path.join(output,'animation-fixtures.json'),JSON.stringify(animations,null,2)+'\n');
  fs.writeFileSync(path.join(output,'model-fixtures.json'),JSON.stringify(models,null,2)+'\n');
  console.log('Prepared the original SIS font, shared fighter data, six stages and 27 playable fighter components in ignored dist/native-port.');
} finally {fs.closeSync(fd);}
